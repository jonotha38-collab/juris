test('existing CNJ is one case; official history and metrics remain intact across OABs',async t=>{
 const {client,api,engine}=await setup();t.after(()=>client.close());
 const first=await api('import','POST',body([{id:10,numero_processo:cnj(1),siglaTribunal:'SEEU',data_disponibilizacao:day(),texto:'Publicação oficial'}]));
 await api('meta/'+cnj(1),'PATCH',{note:'Não sobrescrever'});
 const sheet=await api('import','POST',body([record(1),record(1,{'Número':cnj(1)})]));
 assert.equal(sheet.added,0);assert.equal(sheet.existing,1);assert.equal(sheet.duplicates,1);
 let state=await api('state?view=processes');
 assert.equal(state.total,1);assert.equal(state.rows[0].total,1);assert.equal(state.stats.publications,1);
 assert.equal(state.stats.unread,1);assert.equal(state.rows[0].tribunal,'SEEU');
 assert.equal(state.rows[0].parties.title,'Pessoa de teste 1');
 assert.equal((await api('process/'+cnj(1))).meta.note,'Não sobrescrever');
 await api('import','POST',{...body([record(1)]),oab:'54321',uf:'RJ'});
 state=await api('state?view=processes');assert.equal(state.total,1);assert.equal(state.rows[0].oabs.length,2);
 const rj=await api('state?view=processes&monitor='+encodeURIComponent('office:RJ:54321'));
 assert.equal(rj.total,1);assert.equal(rj.rows[0].total,0);
 assert.equal((await api('state?view=processes&tribunal=SEEU')).total,1);
 const detail=await api('process/'+cnj(1));assert.equal(detail.rows[0].text,'Publicação oficial');assert.equal(detail.count.n,1);
 assert.equal((await api('activity')).totals.publications,1);
 assert.equal((await api('clients/publications/10')).publication.text,'Publicação oficial');
 await assert.rejects(()=>api('clients/publications/catalog:'+cnj(1)),/não encontrada/);
 await api('read','POST',{all:true});assert.equal((await api('state?view=processes')).stats.unread,0);
 assert.equal((await api('export')).items[0].id,10);
 // The same CNJ published by another source label remains one case.
 await engine.saveItems('office',first.monitorId,[{id:11,numero_processo:cnj(1),siglaTribunal:'TJSP',data_disponibilizacao:day(),texto:'Segunda publicação'}]);
 state=await api('state?view=processes');assert.equal(state.total,1);assert.equal(state.stats.publications,2);
});
