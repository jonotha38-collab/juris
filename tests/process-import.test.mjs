import test from 'node:test';
import assert from 'node:assert/strict';
import {createClient} from '@libsql/client';
import {adaptClient} from '../lib/database.mjs';
import {migrate} from '../scripts/migrate.mjs';
import {createEngine,day} from '../core/engine.mjs';
import {classifyImport} from '../public/import-format.mjs';
const cnj=n=>String(n).padStart(20,'0');
const formatted=n=>cnj(n).replace(/^(\d{7})(\d{2})(\d{4})(\d)(\d{2})(\d{4})$/,'$1-$2.$3.$4.$5.$6');
const record=(n,extra={})=>({'Número':formatted(n),'Título':'Pessoa de teste '+n,'Cliente':'Cliente da planilha','Descrição do último histórico':'Texto histórico importado','Data do último histórico':'01/01/2024',...extra});
const body=items=>({oab:'012345',uf:'SP',start:day(),end:day(),items});
async function setup(){
 const client=createClient({url:'file::memory:'}),db=adaptClient(client);await migrate(client);
 const engine=createEngine(db,{mode:'vercel'});
 const api=(path,method='GET',data,owner='office',actorEngine=engine)=>actorEngine.handle(new Request('https://juris.example/api/'+path,{method,...(data===undefined?{}:{headers:{'Content-Type':'application/json'},body:JSON.stringify(data)})}),owner);
 return {client,db,engine,api};
}
test('reads a 720-row spreadsheet array and rejects malformed or oversized files',()=>{
 const rows=Array.from({length:720},(_,i)=>record(i+1));
 assert.equal(classifyImport(rows).records.length,720);
 assert.equal(classifyImport({items:rows}).records.length,720);
 assert.equal(classifyImport([...rows,record(1,{'Número':cnj(1)})]).duplicates,1);
 assert.throws(()=>classifyImport({foo:[]}),/Formato/);
 assert.throws(()=>classifyImport([]),/não contém/);
 assert.throws(()=>classifyImport(Array.from({length:1001},()=>record(1))),/1.000/);
 assert.throws(()=>classifyImport([record(1),{'Número':123}]),/Linha 2/);
 assert.throws(()=>classifyImport([record(1),{id:5,numero_processo:cnj(2)}]),/misture/);
});
